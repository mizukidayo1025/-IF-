"""Write the core's table of `str.casefold` and the fixture its test reads (Issue #152, P8-0a).

Run with the Python whose fold the core copies (CPython 3.12, Unicode 15.0.0):

    python native/core/tools/casefold_table.py

`native/core/src/text/casefold.rs` gets every code point whose `casefold()` is not itself, with
what it folds to. `native/core/tests/data/casefold.txt` gets the same pairs written another way
(hex code points), and the SHA-256 of the folds of all code points, which the core's test
compares with its own fold of each one.
"""

from __future__ import annotations

import hashlib
import sys
import unicodedata
from pathlib import Path

CORE = Path(__file__).resolve().parents[1]
TABLE = CORE / "src" / "text" / "casefold.rs"
FIXTURE = CORE / "tests" / "data" / "casefold.txt"
SURROGATES = range(0xD800, 0xE000)


def code_points() -> list[int]:
    """Every code point a Rust `char` can be: all but the surrogates."""
    return [point for point in range(0x110000) if point not in SURROGATES]


def rust_text(text: str) -> str:
    """A Rust string literal of text, with every code point past ASCII escaped."""
    parts = []
    for char in text:
        point = ord(char)
        if 0x20 <= point < 0x7F and char not in '"\\':
            parts.append(char)
        else:
            parts.append(f"\\u{{{point:x}}}")
    return '"' + "".join(parts) + '"'


def main() -> None:
    version = f"{sys.version_info.major}.{sys.version_info.minor}"
    folds = []
    digest = hashlib.sha256()
    for point in code_points():
        folded = chr(point).casefold()
        digest.update(folded.encode("utf-8"))
        digest.update(b"\0")
        if folded != chr(point):
            folds.append((point, folded))
    rows = "\n".join(f"    ({point:#x}, {rust_text(folded)})," for point, folded in folds)
    TABLE.write_text(
        "//! Generated by `native/core/tools/casefold_table.py` from CPython "
        f"{version}, Unicode {unicodedata.unidata_version}: do not edit.\n"
        "//! Each code point whose `str.casefold` is not itself, in code point order, with its"
        " fold.\n\n"
        f"pub(super) static FOLDS: [(u32, &str); {len(folds)}] = [\n{rows}\n];\n",
        encoding="utf-8",
    )
    lines = [
        f"# str.casefold of CPython {version}, Unicode {unicodedata.unidata_version}"
        " (native/core/tools/casefold_table.py)",
        "# sha256 of the UTF-8 fold of each code point but the surrogates, each followed by a NUL:",
        f"sha256 {digest.hexdigest()}",
        f"count {len(folds)}",
        "# code point, then the code points of its fold, where they differ:",
    ]
    for point, folded in folds:
        lines.append(f"{point:x} " + " ".join(f"{ord(char):x}" for char in folded))
    FIXTURE.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
