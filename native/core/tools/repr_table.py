"""Write the core's table of what `repr(str)` escapes and its test's fixture (Issue #152, P8 c3).

Run with the Python whose `repr` the core copies (CPython 3.12, Unicode 15.0.0):

    python native/core/tools/repr_table.py

`native/core/src/text/printable.rs` gets the ranges of code points past ASCII that `repr` escapes
(those `str.isprintable` says no to). `native/core/tests/data/repr.txt` gets the SHA-256 of the
`repr` of each code point and of a few texts, which the core's test compares with its own.
"""

from __future__ import annotations

import hashlib
import sys
import unicodedata
from pathlib import Path

CORE = Path(__file__).resolve().parents[1]
TABLE = CORE / "src" / "text" / "printable.rs"
FIXTURE = CORE / "tests" / "data" / "repr.txt"
SURROGATES = range(0xD800, 0xE000)
# Texts whose quotes and escapes the test checks as a whole.
TEXTS = [
    "",
    "a'b",
    'a"b',
    "a'\"b",
    "\\",
    "tab\there\nnew\rline",
    "\x00\x7f\x80\xff",
    "避難所",
    "\u2028\U0001f600",
]


def code_points() -> list[int]:
    """Every code point a Rust `char` can be: all but the surrogates."""
    return [point for point in range(0x110000) if point not in SURROGATES]


def escaped_ranges() -> list[tuple[int, int]]:
    """The ranges past ASCII that `str.isprintable` says no to."""
    ranges: list[tuple[int, int]] = []
    start = None
    for point in range(0x80, 0x110000):
        escaped = not chr(point).isprintable()
        if escaped and start is None:
            start = point
        if not escaped and start is not None:
            ranges.append((start, point - 1))
            start = None
    if start is not None:
        ranges.append((start, 0x10FFFF))
    return ranges


def main() -> None:
    version = f"{sys.version_info.major}.{sys.version_info.minor}"
    ranges = escaped_ranges()
    rows = "\n".join(f"    ({first:#x}, {last:#x})," for first, last in ranges)
    TABLE.write_text(
        "//! Generated by `native/core/tools/repr_table.py` from CPython "
        f"{version}, Unicode {unicodedata.unidata_version}: do not edit.\n"
        "//! The ranges of code points past ASCII that `str.isprintable` says no to, which `repr`"
        " escapes.\n\n"
        f"pub(super) static ESCAPED: [(u32, u32); {len(ranges)}] = [\n{rows}\n];\n",
        encoding="utf-8",
    )
    digest = hashlib.sha256()
    for point in code_points():
        digest.update(repr(chr(point)).encode("utf-8"))
        digest.update(b"\0")
    texts = hashlib.sha256()
    for text in TEXTS:
        texts.update(repr(text).encode("utf-8"))
        texts.update(b"\0")
    lines = [
        f"# repr(str) of CPython {version}, Unicode {unicodedata.unidata_version}"
        " (native/core/tools/repr_table.py)",
        "# sha256 of the UTF-8 repr of each code point but the surrogates, each followed by a NUL:",
        f"sha256 {digest.hexdigest()}",
        "# sha256 of the repr of the test's texts, each followed by a NUL:",
        f"texts {texts.hexdigest()}",
        f"ranges {len(ranges)}",
    ]
    FIXTURE.write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
