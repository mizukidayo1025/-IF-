"""Write the core's tables of the character classes of Python's `re` (Issue #294).

Run with the Python whose `re` the core copies (CPython 3.12, Unicode 15.0.0):

    python native/core/tools/regex_classes_table.py

`native/core/src/text/classes.rs` gets the ranges of code points that `\\d`, `\\s` and `\\w` of a
str pattern match (Unicode decimal digits, `str.isspace`, `str.isalnum` and `_`). The parser of
the Scenario text (`scenario/text.rs`) reads them; `tests/unit/llm/test_region_prepare.py`
checks that the file is what this tool writes now.
"""

from __future__ import annotations

import re
import sys
import unicodedata
from pathlib import Path

CORE = Path(__file__).resolve().parents[1]
TABLE = CORE / "src" / "text" / "classes.rs"
CLASSES = (("DECIMAL", r"\d"), ("SPACE", r"\s"), ("WORD", r"\w"))


def ranges(pattern: str) -> list[tuple[int, int]]:
    """The ranges of code points (but the surrogates) that the class matches."""
    compiled = re.compile(pattern)
    found: list[tuple[int, int]] = []
    start = None
    for point in range(0x110001):
        inside = (
            point <= 0x10FFFF
            and not 0xD800 <= point < 0xE000
            and compiled.fullmatch(chr(point)) is not None
        )
        if inside and start is None:
            start = point
        elif not inside and start is not None:
            found.append((start, point - 1))
            start = None
    return found


def text() -> str:
    """The content of the table's file."""
    version = f"{sys.version_info.major}.{sys.version_info.minor}"
    parts = [
        "//! Generated by `native/core/tools/regex_classes_table.py` from CPython "
        f"{version}, Unicode {unicodedata.unidata_version}: do not edit.\n"
        "//! The ranges of code points, inclusive and in order, that `\\d`, `\\s` and `\\w` of a"
        " str pattern of `re` match.\n"
    ]
    for name, pattern in CLASSES:
        found = ranges(pattern)
        rows = "\n".join(f"    ({first:#x}, {last:#x})," for first, last in found)
        parts.append(f"\npub(super) static {name}: [(u32, u32); {len(found)}] = [\n{rows}\n];\n")
    return "".join(parts)


def main() -> None:
    TABLE.write_text(text(), encoding="utf-8")


if __name__ == "__main__":
    main()
